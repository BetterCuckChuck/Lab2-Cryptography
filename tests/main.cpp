#include "aes.hpp"
#include "sp800_38a.hpp"
#include <cassert>
#include <initializer_list>
#include <vector>

static AES::Block block(const std::initializer_list<int>& values) {
    AES::Block result{};
    std::size_t index = 0;
    for (int value : values) result[index++] = static_cast<AES::Byte>(value);
    return result;
}

int main() {
    const auto plaintext = block({0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77,
                                  0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff});
    const std::vector<std::vector<AES::Byte>> keys{
        {0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f},
        {0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
         0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17},
        {0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
         0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f}
    };
    const std::vector<AES::Block> expected{
        block({0x69, 0xc4, 0xe0, 0xd8, 0x6a, 0x7b, 0x04, 0x30, 0xd8, 0xcd, 0xb7, 0x80, 0x70, 0xb4, 0xc5, 0x5a}),
        block({0xdd, 0xa9, 0x7c, 0xa4, 0x86, 0x4c, 0xdf, 0xe0, 0x6e, 0xaf, 0x70, 0xa0, 0xec, 0x0d, 0x71, 0x91}),
        block({0x8e, 0xa2, 0xb7, 0xca, 0x51, 0x67, 0x45, 0xbf, 0xea, 0xfc, 0x49, 0x90, 0x4b, 0x49, 0x60, 0x89})
    };
    for (std::size_t i = 0; i < keys.size(); ++i) {
        const AES aes(keys[i]);
        assert(aes.encrypt(plaintext) == expected[i]);
        assert(aes.decrypt(expected[i]) == plaintext);
    }
    const lab::Bytes data{0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66};
    const lab::Bytes iv(16, 0x00);
    const AES aes(keys[0]);
    assert(lab::ecb_decrypt(aes, lab::ecb_encrypt(aes, data), true) == data);
    assert(lab::cbc_decrypt(aes, lab::cbc_encrypt(aes, data, iv), iv, true) == data);
    assert(lab::cfb_decrypt(aes, lab::cfb_encrypt(aes, data, iv, 8), iv, 8) == data);
    assert(lab::ofb_crypt(aes, lab::ofb_crypt(aes, data, iv), iv) == data);
    assert(lab::ctr_crypt(aes, lab::ctr_crypt(aes, data, iv), iv) == data);
    return 0;
}
