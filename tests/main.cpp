#include "aes.hpp"
#include "sp800_38a.hpp"
#include "sp800_38c.hpp"
#include <algorithm>
#include <iostream>
#include <string>

/*
 * Known-answer test runner for the AES primitive and SP 800-38A/SP 800-38C
 * mode implementations. Expected values come from the NIST publications.
 */

namespace {
using Byte = AES::Byte;
using Bytes = lab::Bytes;

Bytes bytes(std::initializer_list<int> values) {
    // Convert readable integer literals into the project's byte representation.
    Bytes result;
    for (int value : values) result.push_back(static_cast<Byte>(value));
    return result;
}

bool check(const std::string& name, const Bytes& actual, const Bytes& expected) {
    // Keep output compatible with the simple PASS/FAIL test format.
    if (actual != expected) {
        std::cerr << "FAIL " << name << '\n';
        return false;
    }
    std::cout << "PASS " << name << '\n';
    return true;
}
}

int main() {
    // NIST SP 800-38A, Appendix F, AES-128 test vectors.
    const AES aes({0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6,
                   0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f, 0x3c});
    const Bytes plaintext = bytes({
        0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96,
        0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17, 0x2a
    });
    const Bytes iv = bytes({
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
        0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f
    });
    const Bytes counter = bytes({
        0xf0, 0xf1, 0xf2, 0xf3, 0xf4, 0xf5, 0xf6, 0xf7,
        0xf8, 0xf9, 0xfa, 0xfb, 0xfc, 0xfd, 0xfe, 0xff
    });
    const AES::Block aes_plaintext{
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77,
        0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff
    };
    const AES::Block aes_ciphertext = aes.encrypt(aes_plaintext);

    bool all_passed = true;
    all_passed &= check(
        "AES-128",
        Bytes(aes_ciphertext.begin(), aes_ciphertext.end()),
        bytes({0x8d, 0xf4, 0xe9, 0xaa, 0xc5, 0xc7, 0x57, 0x3a,
               0x27, 0xd8, 0xd0, 0x55, 0xd6, 0xe4, 0xd6, 0x4b}));
    all_passed &= check(
        "ECB",
        lab::ecb_encrypt(aes, plaintext, false),
        bytes({0x3a, 0xd7, 0x7b, 0xb4, 0x0d, 0x7a, 0x36, 0x60,
               0xa8, 0x9e, 0xca, 0xf3, 0x24, 0x66, 0xef, 0x97}));
    all_passed &= check(
        "CBC",
        lab::cbc_encrypt(aes, plaintext, iv, false),
        bytes({0x76, 0x49, 0xab, 0xac, 0x81, 0x19, 0xb2, 0x46,
               0xce, 0xe9, 0x8e, 0x9b, 0x12, 0xe9, 0x19, 0x7d}));
    all_passed &= check(
        "CFB128",
        lab::cfb_encrypt(aes, plaintext, iv, 128),
        bytes({0x3b, 0x3f, 0xd9, 0x2e, 0xb7, 0x2d, 0xad, 0x20,
               0x33, 0x34, 0x49, 0xf8, 0xe8, 0x3c, 0xfb, 0x4a}));
    all_passed &= check(
        "CFB8",
        lab::cfb_encrypt(aes, Bytes(plaintext.begin(), plaintext.begin() + 4), iv, 8),
        bytes({0x3b, 0x79, 0x42, 0x4c}));
    all_passed &= check(
        "OFB",
        lab::ofb_crypt(aes, plaintext, iv),
        bytes({0x3b, 0x3f, 0xd9, 0x2e, 0xb7, 0x2d, 0xad, 0x20,
               0x33, 0x34, 0x49, 0xf8, 0xe8, 0x3c, 0xfb, 0x4a}));
    all_passed &= check(
        "CTR",
        lab::ctr_crypt(aes, plaintext, counter),
        bytes({0x87, 0x4d, 0x61, 0x91, 0xb6, 0x20, 0xe3, 0x26,
               0x1b, 0xef, 0x68, 0x64, 0x99, 0x0d, 0xb6, 0xce}));

    // NIST SP 800-38C CCM example.
    const AES ccm_aes({0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47,
                       0x48, 0x49, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f});
    const Bytes ccm_nonce = bytes({0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16});
    const Bytes ccm_aad = bytes({0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07});
    const Bytes ccm_plaintext = bytes({0x20, 0x21, 0x22, 0x23});
    all_passed &= check(
        "CCM",
        lab::ccm_encrypt(ccm_aes, ccm_plaintext, ccm_nonce, ccm_aad, 4, false),
        bytes({0x71, 0x62, 0x01, 0x5b, 0x4d, 0xac, 0x25, 0x5d}));

    if (!all_passed) return 1;
    std::cout << "ALL 8 VECTORS PASS\n";
    return 0;
}
